const byId = new Map(LOOKS.map((l) => [l.id, l]));

/** Preset by id; `none` / unknown / empty resolves to null (Normal). */
export function resolveLook(id) {
  const key = String(id || '').trim().toLowerCase();
  if (!key || key === 'none' || key === 'normal') return null;
  return byId.get(key) || null;
}

export function lookName(id) {
  return resolveLook(id)?.name || 'Normal';
}

/** Small serialisable catalogue for the UI and /api/health. */
export function lookCatalog() {
  return LOOKS.map((l) => ({
    id: l.id,
    name: l.name,
    family: l.family,
    hint: l.hint,
    swatch: l.swatch,
    template: l.caption.template,
    font: l.caption.font,
    accent: l.caption.accent,
  }));
}
